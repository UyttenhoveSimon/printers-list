let current = "en";

export function pickLanguage(saved, preferred) {
  if (saved && STRINGS[saved]) return saved;
  for (const tag of preferred || []) {
    const base = String(tag).slice(0, 2).toLowerCase();
    if (STRINGS[base]) return base;
  }
  return "en";
}

export function setLanguage(lang) {
  current = STRINGS[lang] ? lang : "en";
  return current;
}

export function language() {
  return current;
}

// A missing translation falls back to English, then to the key itself.
export function t(key, values = {}) {
  const text = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
}

export function countryName(code) {
  try {
    return new Intl.DisplayNames([current], { type: "region" }).of(code) || code;
  } catch {
    return code;
  }
}

export function formatNumber(value) {
  return new Intl.NumberFormat(current).format(value);
}

export function missingKeys() {
  // every language must translate what English says, except a few shared words
  const shared = new Set(["wifi", "wifi_direct", "ethernet", "usb", "airprint", "mopria", "nfc", "bluetooth", "led", "unknown", "at_least", "at_most", "g_supplies"]);
  const out = {};
  for (const [lang, strings] of Object.entries(STRINGS)) {
    if (lang === "en") continue;
    out[lang] = Object.keys(STRINGS.en).filter((k) => !(k in strings) && !shared.has(k));
  }
  return out;
}
